import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { readFileSync } from "fs";
import { join } from "path";

const prod = process.argv[2] === "production";

// Read xterm.css and inline it as a string export
const xtermCssPlugin = {
  name: "xterm-css",
  setup(build) {
    build.onResolve({ filter: /xterm\.css$/ }, (args) => ({
      path: args.path,
      namespace: "xterm-css",
    }));
    build.onLoad({ filter: /.*/, namespace: "xterm-css" }, () => {
      const cssPath = join(
        process.cwd(),
        "node_modules",
        "@xterm",
        "xterm",
        "css",
        "xterm.css"
      );
      const css = readFileSync(cssPath, "utf8");
      return {
        contents: `export default ${JSON.stringify(css)};`,
        loader: "js",
      };
    });
  },
};

const context = await esbuild.context({
  banner: {
    js: "/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD — do not edit directly */",
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
  plugins: [xtermCssPlugin],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
